import React, { useState } from 'react';
import { X, UserPlus } from 'lucide-react';
import { api, ApiError } from '../api/client';
import type { Patient } from '../api/types';

interface RegisterPatientModalProps {
  onClose: () => void;
  onCreated: (patient: Patient) => void;
}

const inputClass =
  'w-full rounded-xl border border-slate-200 px-3.5 py-2.5 text-[14px] focus:outline-none focus:border-blue-500 focus:ring-2 focus:ring-blue-100';

// Manual registration while there is no HIS integration.
export const RegisterPatientModal: React.FC<RegisterPatientModalProps> = ({ onClose, onCreated }) => {
  const [form, setForm] = useState({
    hn: '',
    an: '',
    full_name: '',
    gender: '',
    birth_date: '',
    weight_kg: '',
    diagnosis: '',
    ward: 'PICU',
    room: '',
    bed: ''
  });
  const [error, setError] = useState<string | null>(null);
  const [isSaving, setIsSaving] = useState(false);

  const set = (key: keyof typeof form) => (e: React.ChangeEvent<HTMLInputElement | HTMLSelectElement>) =>
    setForm((prev) => ({ ...prev, [key]: e.target.value }));

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setIsSaving(true);
    try {
      // A blank HN is generated by the system (10 digits); a blank name is stored as "ไม่ระบุชื่อ".
      const patient = await api.post<Patient>('/api/patients', {
        hn: form.hn.trim() || null,
        an: form.an.trim() || null,
        full_name: form.full_name.trim() || null,
        gender: form.gender,
        birth_date: form.birth_date || null,
        weight_kg: form.weight_kg ? Number(form.weight_kg) : null,
        diagnosis: form.diagnosis.trim() || null,
        ward: form.ward.trim() || 'PICU',
        room: form.room.trim(),
        bed: form.bed.trim() || null
      });
      onCreated(patient);
    } catch (err) {
      setError(err instanceof ApiError ? err.message : 'ลงทะเบียนผู้ป่วยไม่สำเร็จ');
    } finally {
      setIsSaving(false);
    }
  };

  return (
    <div className="fixed inset-0 bg-slate-900/60 backdrop-blur-xs z-50 flex items-center justify-center p-4 overflow-y-auto animate-fadeIn">
      <form
        onSubmit={handleSubmit}
        className="bg-white rounded-3xl max-w-[640px] w-full p-6 sm:p-7 space-y-5 shadow-2xl relative border border-slate-100 max-h-[92vh] overflow-y-auto"
      >
        <button
          type="button"
          onClick={onClose}
          className="absolute top-6 right-6 w-9 h-9 rounded-full bg-slate-100 hover:bg-slate-200 text-slate-500 flex items-center justify-center cursor-pointer"
        >
          <X className="w-5 h-5" />
        </button>
        <div>
          <span className="text-[11px] font-bold text-[#1E58E6] tracking-wider uppercase block">PEDIVEINCARE AI</span>
          <h2 className="text-xl sm:text-2xl font-extrabold text-slate-900 tracking-tight mt-0.5">ลงทะเบียนผู้ป่วยเด็ก</h2>
          <p className="text-slate-500 text-[13px] mt-0.5">ต้องกรอกเฉพาะห้องและเพศ · ช่องอื่นเว้นว่างได้</p>
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 text-[13px]">
          <label className="space-y-1.5">
            <span className="font-semibold text-slate-700">HN</span>
            <input
              value={form.hn}
              onChange={set('hn')}
              placeholder="เว้นว่างได้ ระบบจะสร้าง HN 10 หลักให้"
              className={inputClass}
            />
          </label>
          <label className="space-y-1.5">
            <span className="font-semibold text-slate-700">AN</span>
            <input value={form.an} onChange={set('an')} className={inputClass} />
          </label>
          <label className="space-y-1.5 sm:col-span-2">
            <span className="font-semibold text-slate-700">ชื่อ-นามสกุล</span>
            <input value={form.full_name} onChange={set('full_name')} placeholder="ไม่บังคับ" className={inputClass} />
          </label>
          <label className="space-y-1.5">
            <span className="font-semibold text-slate-700">เพศ *</span>
            <select required value={form.gender} onChange={set('gender')} className={inputClass}>
              <option value="" disabled>เลือกเพศ</option>
              <option value="male">ชาย</option>
              <option value="female">หญิง</option>
              <option value="other">อื่นๆ</option>
            </select>
          </label>
          <label className="space-y-1.5">
            <span className="font-semibold text-slate-700">วันเกิด</span>
            <input type="date" value={form.birth_date} onChange={set('birth_date')} className={inputClass} />
          </label>
          <label className="space-y-1.5">
            <span className="font-semibold text-slate-700">น้ำหนัก (กก.)</span>
            <input type="number" step="0.1" min="0" value={form.weight_kg} onChange={set('weight_kg')} className={inputClass} />
          </label>
          <label className="space-y-1.5">
            <span className="font-semibold text-slate-700">การวินิจฉัย</span>
            <input value={form.diagnosis} onChange={set('diagnosis')} className={inputClass} />
          </label>
          <label className="space-y-1.5">
            <span className="font-semibold text-slate-700">หอผู้ป่วย</span>
            <input value={form.ward} onChange={set('ward')} className={inputClass} />
          </label>
          <div className="grid grid-cols-2 gap-3">
            <label className="space-y-1.5">
              <span className="font-semibold text-slate-700">ห้อง *</span>
              <input required value={form.room} onChange={set('room')} className={inputClass} />
            </label>
            <label className="space-y-1.5">
              <span className="font-semibold text-slate-700">เตียง</span>
              <input value={form.bed} onChange={set('bed')} className={inputClass} />
            </label>
          </div>
        </div>

        {error && (
          <div className="rounded-xl border border-red-200 bg-red-50 px-4 py-2.5 text-[13px] font-medium text-red-700">{error}</div>
        )}

        <div className="flex items-center justify-end gap-3 pt-2">
          <button
            type="button"
            onClick={onClose}
            className="px-6 py-2.5 bg-white border border-slate-200 hover:bg-slate-50 text-slate-700 rounded-xl font-bold text-[14px] cursor-pointer"
          >
            ยกเลิก
          </button>
          <button
            type="submit"
            disabled={isSaving}
            className="px-5 py-2.5 rounded-xl font-bold text-[14px] flex items-center gap-2 bg-[#1E58E6] hover:bg-blue-700 text-white shadow-xs cursor-pointer disabled:opacity-60"
          >
            <UserPlus className="w-4 h-4" />
            <span>{isSaving ? 'กำลังบันทึก...' : 'ลงทะเบียนผู้ป่วย'}</span>
          </button>
        </div>
      </form>
    </div>
  );
};
